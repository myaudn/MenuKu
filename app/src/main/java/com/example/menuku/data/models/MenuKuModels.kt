    val description: String,
    val coverUrl: String,
    val recipeCount: Int,
    val difficulty: String = "Semua Mudah",
    val authorNote: String,
    val iconName: String = "eco",
    val themeColor: String = "hijau",
    val recipeIds: List<String> = emptyList()
