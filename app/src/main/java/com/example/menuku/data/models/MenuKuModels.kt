data class StorageLocation(
    val id: String,
    val label: String,
    val tempDesc: String
) {
    companion object {
        val KULKAS = StorageLocation("kulkas", "Kulkas Utama", "Chiller 2°C - 4°C")
        val FREEZER = StorageLocation("freezer", "Freezer", "Beku -18°C")
        val PANTRI = StorageLocation("pantri", "Pantri / Rak", "Suhu Ruang")
    }
}

data class StockItem(
    val id: String,
    val name: String,
    val quantity: Double,
    val unit: String,
    val location: StorageLocation,
    val category: String, // Daging & Telur, Sayur & Buah, Bumbu Rempah, Susu & Olahan, Sembako
    val purchaseDate: String,
    val expiryDate: String,
    val remainingDays: Int,
    val imageUrl: String = "",
    val note: String = "",
    val matchedRecipes: List<String> = emptyList()
) {
    val isUrgent: Boolean get() = remainingDays <= 2
    val statusColorType: String get() = when {
        remainingDays <= 2 -> "CRITICAL"
        remainingDays <= 4 -> "WARNING"
        else -> "GOOD"
    }
}

enum class MealSlot(val label: String, val defaultTime: String, val icon: String) {
    SARAPAN("Sarapan", "07:00 WIB", "wb_twilight"),
    SIANG("Makan Siang", "12:30 WIB", "sunny"),
    CAMILAN("Camilan Sore", "16:00 WIB", "cookie"),
    MALAM("Makan Malam", "19:00 WIB", "bedtime")
}

data class MealSchedule(
    val id: String,
    val dateStr: String, // e.g. "2024-11-21"
    val dayName: String, // e.g. "Kamis"
    val dayNumber: Int, // e.g. 21
    val slot: MealSlot,
    val recipe: Recipe? = null,
    val recipes: List<Recipe> = emptyList(),
    val isReadyInFridge: Boolean = true,
    val reminderTime: String = "11:15 WIB",
    val reminderEnabled: Boolean = true,
    val note: String = "",
    val autoSyncGrocery: Boolean = true
) {
    val allRecipes: List<Recipe> get() = recipes.ifEmpty { listOfNotNull(recipe) }
}

