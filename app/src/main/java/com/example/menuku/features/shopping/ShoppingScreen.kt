package com.example.menuku.features.shopping

import androidx.compose.foundation.background
import androidx.compose.foundation.clickable
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.LazyRow
import androidx.compose.foundation.lazy.items
import androidx.compose.foundation.shape.CircleShape
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.platform.testTag
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.example.menuku.core.components.EmptyStateView
import com.example.menuku.core.components.MenuKuTopBar
import com.example.menuku.core.navigation.Screen
import com.example.menuku.data.models.UrgencyLevel
import com.example.menuku.data.repository.MenuKuRepository
import com.example.ui.theme.*

@Composable
fun ShoppingScreen(
    repository: MenuKuRepository,
    onNavigate: (String) -> Unit
) {
    val items by repository.shoppingItems.collectAsState()

    var selectedFilter by remember { mutableStateOf("Semua") }
    val filters = listOf("Semua", "Otomatis Resep", "Manual", "Belum Dibeli", "Sudah Dibeli")

    val filteredItems = items.filter { item ->
        when (selectedFilter) {
            "Otomatis Resep" -> item.isAutoGenerated
            "Manual" -> !item.isAutoGenerated
            "Belum Dibeli" -> !item.isPurchased
            "Sudah Dibeli" -> item.isPurchased
            else -> true
        }
    }

    val totalEstimatedPrice = items.filter { !it.isPurchased }.sumOf { it.estimatedPrice }

    Scaffold(
        topBar = {
            MenuKuTopBar(
                title = "Daftar Belanja",
                subtitle = "Otomatis & Manual Ditambahkan",
                onNotificationClick = { onNavigate(Screen.NotificationCenter.route) },
                onProfileClick = { onNavigate(Screen.Profile.route) }
            )
        },
        floatingActionButton = {
            ExtendedFloatingActionButton(
                onClick = { onNavigate(Screen.AddShoppingItem.route) },
                containerColor = MenuKuOrangeContainer,
                contentColor = Color.White,
                shape = RoundedCornerShape(18.dp),
                modifier = Modifier.testTag("shopping_add_fab")
            ) {
                Icon(imageVector = Icons.Default.Add, contentDescription = null)
                Spacer(modifier = Modifier.width(6.dp))
                Text("Tambah Item", fontWeight = FontWeight.Bold)
            }
        },
        containerColor = MaterialTheme.colorScheme.surface,
        contentWindowInsets = WindowInsets(0, 0, 0, 0)
    ) { innerPadding ->
        LazyColumn(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
                .testTag("shopping_screen_list"),
            contentPadding = PaddingValues(horizontal = 16.dp, vertical = 8.dp),
            verticalArrangement = Arrangement.spacedBy(14.dp)
        ) {
            // Budget Summary Card
            item {
                Card(
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(20.dp),
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceContainerLow)
                ) {
                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(16.dp),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Row(
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.spacedBy(12.dp)
                        ) {
                            Box(
                                modifier = Modifier
                                    .size(44.dp)
                                    .clip(CircleShape)
                                    .background(MenuKuGreenLight),
                                contentAlignment = Alignment.Center
                            ) {
                                Icon(
                                    imageVector = Icons.Default.Payments,
                                    contentDescription = null,
                                    tint = MenuKuGreenPrimary
                                )
                            }
                            Column {
                                Text("Estimasi Kebutuhan Belanja", style = MaterialTheme.typography.labelSmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                                Text("Rp ${String.format("%,d", totalEstimatedPrice).replace(',', '.')}", style = MaterialTheme.typography.headlineSmall, fontWeight = FontWeight.Bold, color = MenuKuGreenPrimary)
                            }
                        }

                        Surface(shape = CircleShape, color = MenuKuGreenLight) {
                            Text(
                                text = "${items.count { !it.isPurchased }} Item",
                                style = MaterialTheme.typography.labelSmall,
                                fontWeight = FontWeight.Bold,
                                color = MenuKuGreenPrimary,
                                modifier = Modifier.padding(horizontal = 10.dp, vertical = 4.dp)
                            )
                        }
                    }
                }
            }

            // Filter Tabs
            item {
                LazyRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    items(filters) { filter ->
                        val isSelected = selectedFilter == filter
                        val count = when (filter) {
                            "Otomatis Resep" -> items.count { it.isAutoGenerated }
                            "Manual" -> items.count { !it.isAutoGenerated }
                            "Belum Dibeli" -> items.count { !it.isPurchased }
                            "Sudah Dibeli" -> items.count { it.isPurchased }
                            else -> items.size
                        }

                        FilterChip(
                            selected = isSelected,
                            onClick = { selectedFilter = filter },
                            label = { Text("$filter ($count)") },
                            shape = CircleShape,
                            colors = FilterChipDefaults.filterChipColors(
                                selectedContainerColor = MenuKuGreenPrimary,
                                selectedLabelColor = Color.White,
                                containerColor = MaterialTheme.colorScheme.surfaceContainerHigh
                            ),
                            border = null
                        )
                    }
                }
            }

            // Empty State or List
            if (filteredItems.isEmpty()) {
                item {
                    EmptyStateView(
                        icon = Icons.Default.ShoppingBag,
                        title = "Daftar Belanja Kosong",
                        description = "Tambahkan item belanja manual atau sinkronkan resep terjadwal yang kurang bahan.",
                        actionButtonText = "+ Tambah Item Belanja",
                        onActionClick = { onNavigate(Screen.AddShoppingItem.route) }
                    )
                }
            } else {
                items(filteredItems) { item ->
                    Card(
                        modifier = Modifier
                            .fillMaxWidth()
                            .clickable { onNavigate(Screen.ShoppingItemDetail.createRoute(item.id)) }
                            .testTag("shopping_item_card_${item.id}"),
                        shape = RoundedCornerShape(18.dp),
                        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceContainerLowest),
                        elevation = CardDefaults.cardElevation(defaultElevation = 1.dp)
                    ) {
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(16.dp),
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.spacedBy(12.dp)
                        ) {
                            Checkbox(
                                checked = item.isPurchased,
                                onCheckedChange = { repository.toggleShoppingItemPurchased(item.id) },
                                colors = CheckboxDefaults.colors(checkedColor = MenuKuGreenPrimary)
                            )

                            Column(
                                modifier = Modifier.weight(1f),
                                verticalArrangement = Arrangement.spacedBy(6.dp)
                            ) {
                                // 1. Item Name
                                Text(
                                    text = item.name,
                                    style = MaterialTheme.typography.titleSmall,
                                    fontWeight = FontWeight.Bold,
                                    color = if (item.isPurchased) MaterialTheme.colorScheme.outline else MaterialTheme.colorScheme.onSurface
                                )

                                // 2. Badges Below Item Name (Otomatis Resep / Manual & Penting)
                                Row(
                                    horizontalArrangement = Arrangement.spacedBy(6.dp),
                                    verticalAlignment = Alignment.CenterVertically
                                ) {
                                    if (item.isAutoGenerated) {
                                        Surface(shape = CircleShape, color = MenuKuGreenLight) {
                                            Text(
                                                text = "Otomatis Resep",
                                                style = MaterialTheme.typography.labelSmall,
                                                fontWeight = FontWeight.Bold,
                                                color = MenuKuGreenPrimary,
                                                fontSize = 10.sp,
                                                modifier = Modifier.padding(horizontal = 8.dp, vertical = 2.dp)
                                            )
                                        }
                                    } else {
                                        Surface(shape = CircleShape, color = MaterialTheme.colorScheme.surfaceContainerHighest) {
                                            Text(
                                                text = "Manual",
                                                style = MaterialTheme.typography.labelSmall,
                                                fontWeight = FontWeight.Bold,
                                                color = MaterialTheme.colorScheme.onSurfaceVariant,
                                                fontSize = 10.sp,
                                                modifier = Modifier.padding(horizontal = 8.dp, vertical = 2.dp)
                                            )
                                        }
                                    }

                                    if (item.urgency == UrgencyLevel.URGENT && !item.isPurchased) {
                                        Surface(shape = CircleShape, color = MenuKuOrangeLight) {
                                            Text(
                                                text = "Penting",
                                                style = MaterialTheme.typography.labelSmall,
                                                fontWeight = FontWeight.Bold,
                                                color = MenuKuOrange,
                                                fontSize = 10.sp,
                                                modifier = Modifier.padding(horizontal = 8.dp, vertical = 2.dp)
                                            )
                                        }
                                    }
                                }

                                // 3. Quantity & Estimated Price
                                val formattedQty = if (item.quantity % 1.0 == 0.0) item.quantity.toInt().toString() else item.quantity.toString()
                                Text(
                                    text = "$formattedQty ${item.unit} • Est. Rp ${String.format("%,d", item.estimatedPrice).replace(',', '.')}",
                                    style = MaterialTheme.typography.bodySmall,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant
                                )

                                // 4. Linked Recipe Menu
                                if (item.linkedRecipeTitle.isNotBlank()) {
                                    Text(
                                        text = "Menu: ${item.linkedRecipeTitle}",
                                        style = MaterialTheme.typography.labelSmall,
                                        color = MenuKuGreenPrimary,
                                        fontWeight = FontWeight.Medium
                                    )
                                }
                            }

                            // 5. Action Button (Beli / Sudah)
                            Surface(
                                shape = CircleShape,
                                color = if (item.isPurchased) MenuKuGreenLight else MaterialTheme.colorScheme.surfaceContainerHigh
                            ) {
                                Text(
                                    text = if (item.isPurchased) "Sudah" else "Beli",
                                    style = MaterialTheme.typography.labelSmall,
                                    fontWeight = FontWeight.Bold,
                                    color = if (item.isPurchased) MenuKuGreenPrimary else MaterialTheme.colorScheme.onSurfaceVariant,
                                    modifier = Modifier.padding(horizontal = 10.dp, vertical = 5.dp)
                                )
                            }
                        }
                    }
                }
            }

            item {
                Spacer(modifier = Modifier.height(64.dp))
            }
        }
    }
}
